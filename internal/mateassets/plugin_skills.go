package mateassets

import (
	"bufio"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// PluginSkillPrefix starts the directory name of every plugin skill. No
// built-in skill (SkillNames) takes it.
const PluginSkillPrefix = "plugin-"

// ErrPluginSkillConflict is a plugin skill's destination holding something
// WritePluginSkills did not write.
var ErrPluginSkillConflict = errors.New("plugin skill destination holds content mate did not generate")

// PluginSkill is one skill a plugin instance gives a Mate. It mirrors
// plugin.Skill, so this package does not depend on internal/plugin.
type PluginSkill struct {
	Instance string
	Name     string
	Content  []byte
}

// PluginSkillMarker is the first line of every SKILL.md WritePluginSkills
// writes for instance. It is what marks the directory as generated: one
// whose SKILL.md opens with it may be rewritten or removed, anything else is
// the user's.
func PluginSkillMarker(instance string) string {
	return "<!-- generated by mate plugin " + instance + "; do not edit -->"
}

// PluginSkillDir is the directory name, under the skills directory, of
// instance's skill name.
func PluginSkillDir(instance, name string) string {
	return PluginSkillPrefix + instance + "-" + name
}

var (
	pluginPartRe   = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]*$`)
	pluginMarkerRe = regexp.MustCompile(`^<!-- generated by mate plugin ([A-Za-z0-9][A-Za-z0-9._-]*); do not edit -->$`)
)

// WritePluginSkills installs skills under <dir>/<skillsDir>/plugin-<instance>-<name>/SKILL.md,
// the marker line first and then the skill's content, and removes every
// plugin-* directory a previous call generated that skills no longer has (an
// instance disabled or unbound). It never touches a built-in skill or a
// directory whose SKILL.md does not open with the marker of the instance its
// name carries. A destination that exists and is not this generator's - a
// SKILL.md without the marker, other files, a file or a symlink - is
// ErrPluginSkillConflict naming its path, and then nothing is written or
// removed.
func WritePluginSkills(dir, skillsDir string, skills []PluginSkill) error {
	if !filepath.IsLocal(filepath.FromSlash(skillsDir)) {
		return fmt.Errorf("mateassets: skills directory %q is not a relative path inside the Mate's directory", skillsDir)
	}
	root := filepath.Join(dir, filepath.FromSlash(skillsDir))
	want := make(map[string]PluginSkill, len(skills))
	order := make([]string, 0, len(skills))
	for _, s := range skills {
		if !pluginPartRe.MatchString(s.Instance) || !pluginPartRe.MatchString(s.Name) {
			return fmt.Errorf("mateassets: plugin skill %q of instance %q: instance and name must match %s", s.Name, s.Instance, pluginPartRe)
		}
		name := PluginSkillDir(s.Instance, s.Name)
		if prev, ok := want[name]; ok {
			return fmt.Errorf("mateassets: plugin skills %s/%s and %s/%s both go to %s", prev.Instance, prev.Name, s.Instance, s.Name, filepath.Join(root, name))
		}
		want[name] = s
		order = append(order, name)
	}

	for _, name := range order {
		if err := checkPluginSkillDir(filepath.Join(root, name)); err != nil {
			return err
		}
	}
	stale, err := stalePluginSkills(root, want)
	if err != nil {
		return err
	}
	for _, path := range stale {
		if err := os.RemoveAll(path); err != nil {
			return err
		}
	}
	for _, name := range order {
		s := want[name]
		skillDir := filepath.Join(root, name)
		if err := os.MkdirAll(skillDir, 0o755); err != nil {
			return err
		}
		data := make([]byte, 0, len(PluginSkillMarker(s.Instance))+1+len(s.Content))
		data = append(data, PluginSkillMarker(s.Instance)+"\n"...)
		data = append(data, s.Content...)
		if err := writeAtomic(filepath.Join(skillDir, "SKILL.md"), data); err != nil {
			return err
		}
	}
	return nil
}

// checkPluginSkillDir refuses a destination that holds anything but this
// generator's output: it may be missing, empty, or a directory whose
// SKILL.md opens with the marker of the instance its name carries.
func checkPluginSkillDir(path string) error {
	conflict := func(why string) error {
		return fmt.Errorf("%w: %s %s; move it away or rename it, mate will not overwrite it", ErrPluginSkillConflict, path, why)
	}
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !info.IsDir() {
		return conflict("is not a directory")
	}
	if generatedPluginSkill(path) {
		return nil
	}
	entries, err := os.ReadDir(path)
	if err != nil {
		return err
	}
	if len(entries) == 0 {
		return nil
	}
	return conflict("has a SKILL.md or files without the mate plugin marker on the first line")
}

// stalePluginSkills are the generated plugin-* directories under root that
// want does not keep.
func stalePluginSkills(root string, want map[string]PluginSkill) ([]string, error) {
	entries, err := os.ReadDir(root)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var stale []string
	for _, e := range entries {
		if !e.IsDir() || !strings.HasPrefix(e.Name(), PluginSkillPrefix) {
			continue
		}
		if _, ok := want[e.Name()]; ok {
			continue
		}
		path := filepath.Join(root, e.Name())
		if generatedPluginSkill(path) {
			stale = append(stale, path)
		}
	}
	return stale, nil
}

// generatedPluginSkill reports whether dir is a directory (not a symlink)
// whose SKILL.md is a regular file opening with the marker of an instance
// that dir's name starts with.
func generatedPluginSkill(dir string) bool {
	if info, err := os.Lstat(dir); err != nil || !info.IsDir() {
		return false
	}
	path := filepath.Join(dir, "SKILL.md")
	if info, err := os.Lstat(path); err != nil || !info.Mode().IsRegular() {
		return false
	}
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	line, err := bufio.NewReader(io.LimitReader(f, 512)).ReadString('\n')
	if err != nil && !errors.Is(err, io.EOF) {
		return false
	}
	m := pluginMarkerRe.FindStringSubmatch(strings.TrimRight(line, "\r\n"))
	return m != nil && strings.HasPrefix(filepath.Base(dir), PluginSkillPrefix+m[1]+"-")
}
