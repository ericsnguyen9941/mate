package mateassets

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// PluginSkillPrefix starts the directory name of every plugin skill. No
// built-in skill (SkillNames) takes it.
const PluginSkillPrefix = "plugin-"

// ErrPluginSkillConflict is a plugin skill's destination holding something
// WritePluginSkills did not write.
var ErrPluginSkillConflict = errors.New("plugin skill destination holds content mate did not generate")

// PluginSkill is one skill a plugin instance gives a Mate. It mirrors
// plugin.Skill, so this package does not depend on internal/plugin.
type PluginSkill struct {
	Instance string
	Name     string
	Content  []byte
}

// PluginSkillMarker is the line WritePluginSkills adds to every SKILL.md it
// writes for instance, at the position pluginMarkerAt names: the first line,
// or, for a skill that opens with YAML frontmatter, the line right after the
// frontmatter's closing "---", so the harness still reads the frontmatter.
// It is what marks the directory as generated: one whose SKILL.md carries it
// at that position may be rewritten or removed, anything else is the user's.
func PluginSkillMarker(instance string) string {
	return "<!-- generated by mate plugin " + instance + "; do not edit -->"
}

// PluginSkillDir is the directory name, under the skills directory, of
// instance's skill name.
func PluginSkillDir(instance, name string) string {
	return PluginSkillPrefix + instance + "-" + name
}

// maxPluginSkillFrontmatter is how far into a skill its frontmatter's
// closing "---" line may end. A skill whose frontmatter is not closed
// within it is refused, and a file like it is not generated.
const maxPluginSkillFrontmatter = 64 << 10

var (
	pluginPartRe   = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]*$`)
	pluginMarkerRe = regexp.MustCompile(`^<!-- generated by mate plugin ([A-Za-z0-9][A-Za-z0-9._-]*); do not edit -->$`)
)

// WritePluginSkills installs skills under <dir>/<skillsDir>/plugin-<instance>-<name>/SKILL.md,
// the skill's content with the marker line at its position (PluginSkillMarker),
// and removes every plugin-* directory a previous call generated that skills
// no longer has (an instance disabled or unbound). It never touches a
// built-in skill or a directory whose SKILL.md does not carry, at that
// position, the marker of the instance its name carries. A destination that
// exists and is not this generator's - a SKILL.md without the marker there,
// other files, a file or a symlink - is ErrPluginSkillConflict naming its
// path, and a skill whose frontmatter is not closed within
// maxPluginSkillFrontmatter is refused; either way nothing is written or
// removed.
func WritePluginSkills(dir, skillsDir string, skills []PluginSkill) error {
	if !filepath.IsLocal(filepath.FromSlash(skillsDir)) {
		return fmt.Errorf("mateassets: skills directory %q is not a relative path inside the Mate's directory", skillsDir)
	}
	root := filepath.Join(dir, filepath.FromSlash(skillsDir))
	want := make(map[string]PluginSkill, len(skills))
	files := make(map[string][]byte, len(skills))
	order := make([]string, 0, len(skills))
	for _, s := range skills {
		if !pluginPartRe.MatchString(s.Instance) || !pluginPartRe.MatchString(s.Name) {
			return fmt.Errorf("mateassets: plugin skill %q of instance %q: instance and name must match %s", s.Name, s.Instance, pluginPartRe)
		}
		name := PluginSkillDir(s.Instance, s.Name)
		if prev, ok := want[name]; ok {
			return fmt.Errorf("mateassets: plugin skills %s/%s and %s/%s both go to %s", prev.Instance, prev.Name, s.Instance, s.Name, filepath.Join(root, name))
		}
		data, err := renderPluginSkill(s)
		if err != nil {
			return err
		}
		want[name] = s
		files[name] = data
		order = append(order, name)
	}

	for _, name := range order {
		if err := checkPluginSkillDir(filepath.Join(root, name)); err != nil {
			return err
		}
	}
	stale, err := stalePluginSkills(root, want)
	if err != nil {
		return err
	}
	for _, path := range stale {
		if err := os.RemoveAll(path); err != nil {
			return err
		}
	}
	for _, name := range order {
		skillDir := filepath.Join(root, name)
		if err := os.MkdirAll(skillDir, 0o755); err != nil {
			return err
		}
		if err := writeAtomic(filepath.Join(skillDir, "SKILL.md"), files[name]); err != nil {
			return err
		}
	}
	return nil
}

// renderPluginSkill is s's SKILL.md: its content with the marker line
// inserted at pluginMarkerAt. After a closing "---" that ends the content
// without a newline, one is added first, in the frontmatter's line ending.
func renderPluginSkill(s PluginSkill) ([]byte, error) {
	at, eol, ok := pluginMarkerAt(s.Content)
	if !ok {
		return nil, fmt.Errorf("mateassets: plugin skill %q of instance %q opens a YAML frontmatter (---) that is not closed within %d bytes", s.Name, s.Instance, maxPluginSkillFrontmatter)
	}
	marker := PluginSkillMarker(s.Instance)
	data := make([]byte, 0, len(s.Content)+len(marker)+2*len(eol))
	data = append(data, s.Content[:at]...)
	if at > 0 && s.Content[at-1] != '\n' {
		data = append(data, eol...)
	}
	data = append(data, marker...)
	data = append(data, eol...)
	return append(data, s.Content[at:]...), nil
}

// pluginMarkerAt is the byte offset of the marker line in a skill: 0, or,
// when the first line is "---", the end of the next "---" line (CRLF or LF),
// which must end within maxPluginSkillFrontmatter bytes; ok is false when it
// does not. eol is the line ending the marker takes: the frontmatter's
// (its closing line's, or its opening line's when the closing one ends the
// data), or "\n" without frontmatter.
func pluginMarkerAt(data []byte) (at int, eol string, ok bool) {
	line, rest, nl := cutLine(data)
	if string(line) != "---" {
		return 0, "\n", true
	}
	if !nl {
		return 0, "", false
	}
	at = len(data) - len(rest)
	eol = "\n"
	if bytes.HasSuffix(data[:at], []byte("\r\n")) {
		eol = "\r\n"
	}
	for at < len(data) && at <= maxPluginSkillFrontmatter {
		line, rest, nl = cutLine(data[at:])
		end := len(data) - len(rest)
		if end > maxPluginSkillFrontmatter {
			return 0, "", false
		}
		if string(line) == "---" {
			if nl {
				eol = "\n"
				if bytes.HasSuffix(data[at:end], []byte("\r\n")) {
					eol = "\r\n"
				}
			}
			return end, eol, true
		}
		if !nl {
			break
		}
		at = end
	}
	return 0, "", false
}

// cutLine splits data at its first newline: the line without its "\n" or
// "\r\n", what follows, and whether there was a newline at all.
func cutLine(data []byte) (line, rest []byte, nl bool) {
	line, rest, nl = bytes.Cut(data, []byte("\n"))
	return bytes.TrimSuffix(line, []byte("\r")), rest, nl
}

// checkPluginSkillDir refuses a destination that holds anything but this
// generator's output: it may be missing, empty, or a directory
// generatedPluginSkill recognises.
func checkPluginSkillDir(path string) error {
	conflict := func(why string) error {
		return fmt.Errorf("%w: %s %s; move it away or rename it, mate will not overwrite it", ErrPluginSkillConflict, path, why)
	}
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !info.IsDir() {
		return conflict("is not a directory")
	}
	if generatedPluginSkill(path) {
		return nil
	}
	entries, err := os.ReadDir(path)
	if err != nil {
		return err
	}
	if len(entries) == 0 {
		return nil
	}
	return conflict("has a SKILL.md or files without the mate plugin marker where mate writes it")
}

// stalePluginSkills are the generated plugin-* directories under root that
// want does not keep.
func stalePluginSkills(root string, want map[string]PluginSkill) ([]string, error) {
	entries, err := os.ReadDir(root)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var stale []string
	for _, e := range entries {
		if !e.IsDir() || !strings.HasPrefix(e.Name(), PluginSkillPrefix) {
			continue
		}
		if _, ok := want[e.Name()]; ok {
			continue
		}
		path := filepath.Join(root, e.Name())
		if generatedPluginSkill(path) {
			stale = append(stale, path)
		}
	}
	return stale, nil
}

// generatedPluginSkill reports whether dir is a directory (not a symlink)
// whose SKILL.md is a regular file carrying, exactly at pluginMarkerAt, the
// marker of an instance that dir's name starts with.
func generatedPluginSkill(dir string) bool {
	if info, err := os.Lstat(dir); err != nil || !info.IsDir() {
		return false
	}
	path := filepath.Join(dir, "SKILL.md")
	if info, err := os.Lstat(path); err != nil || !info.Mode().IsRegular() {
		return false
	}
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	// The frontmatter, then the marker line, which is short.
	data, err := io.ReadAll(io.LimitReader(f, maxPluginSkillFrontmatter+4<<10))
	if err != nil {
		return false
	}
	at, _, ok := pluginMarkerAt(data)
	if !ok {
		return false
	}
	line, rest, _ := cutLine(data[at:])
	m := pluginMarkerRe.FindSubmatch(line)
	if m == nil {
		return false
	}
	// The content without the marker must put it back where it is: a
	// marker above a frontmatter, say, is not where mate writes one.
	content := append(append([]byte(nil), data[:at]...), rest...)
	if back, _, ok := pluginMarkerAt(content); !ok || back != at {
		return false
	}
	return strings.HasPrefix(filepath.Base(dir), PluginSkillPrefix+string(m[1])+"-")
}
