// A generated skill no longer resolved (instance disabled or unbound) is
// removed; nothing else in the skills directory is touched.
func TestWritePluginSkillsRemovesStaleOnly(t *testing.T) {
	dir := t.TempDir()
	if err := WritePluginSkills(dir, testSkillsDir, []PluginSkill{
		{Instance: "gone", Name: "workflow", Content: []byte("g\n")},
		{Instance: "kept", Name: "workflow", Content: []byte("k\n")},
	}); err != nil {
		t.Fatal(err)
	}
	builtin := SkillNames[0]
	untouched := map[string]string{
		builtin: "built-in\n",
		"foo":   "# user skill\n",
		// plugin-* without the marker is the user's, not stale output.
		"plugin-mine-x": "# user skill named like a plugin\n",
		// A marker whose instance is not the directory's is not this
		// generator's output for that directory.
		"plugin-other-x": PluginSkillMarker("someone") + "\nx\n",
	}
	for name, text := range untouched {
		writeSkillFile(t, dir, name, text)
	}
	if err := os.WriteFile(filepath.Join(dir, testSkillsDir, "plugin-loose-file"), []byte(PluginSkillMarker("loose")), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := WritePluginSkills(dir, testSkillsDir, []PluginSkill{{Instance: "kept", Name: "workflow", Content: []byte("k2\n")}}); err != nil {
		t.Fatal(err)
	}
	if exists(t, filepath.Join(dir, testSkillsDir, "plugin-gone-workflow")) {
		t.Error("stale plugin skill was not removed")
	}
	if got := readSkill(t, dir, "plugin-kept-workflow"); got != PluginSkillMarker("kept")+"\nk2\n" {
		t.Errorf("kept skill = %q", got)
	}
	for name, text := range untouched {
		if got := readSkill(t, dir, name); got != text {
			t.Errorf("%s changed: %q", name, got)
		}
	}
	if !exists(t, filepath.Join(dir, testSkillsDir, "plugin-loose-file")) {
		t.Error("a plain file named plugin-* was removed")
	}

	// No plugin left: the last generated skill goes too.
	if err := WritePluginSkills(dir, testSkillsDir, nil); err != nil {
		t.Fatal(err)
	}
	if exists(t, filepath.Join(dir, testSkillsDir, "plugin-kept-workflow")) {
		t.Error("last plugin skill was not removed")
	}
}

