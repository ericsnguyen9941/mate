const testSkillsDir = ".claude/skills"

func readSkill(t *testing.T, dir, name string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(dir, testSkillsDir, name, "SKILL.md"))
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func writeSkillFile(t *testing.T, dir, name, text string) string {
	t.Helper()
	path := filepath.Join(dir, testSkillsDir, name, "SKILL.md")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

func exists(t *testing.T, path string) bool {
	t.Helper()
	_, err := os.Lstat(path)
	if err != nil && !os.IsNotExist(err) {
		t.Fatal(err)
	}
	return err == nil
}

// Two instances of one package both give a skill named "workflow"; the
// directory carries the instance, so neither overwrites the other.
func TestWritePluginSkillsNamespacesByInstance(t *testing.T) {
	dir := t.TempDir()
	skills := []PluginSkill{
		{Instance: "tracker-work", Name: "workflow", Content: []byte("# Work\n")},
		{Instance: "tracker-home", Name: "workflow", Content: []byte("# Home\n")},
	}
	if err := WritePluginSkills(dir, testSkillsDir, skills); err != nil {
		t.Fatal(err)
	}
	for _, s := range skills {
		got := readSkill(t, dir, "plugin-"+s.Instance+"-"+s.Name)
		want := "<!-- generated by mate plugin " + s.Instance + "; do not edit -->\n" + string(s.Content)
		if got != want {
			t.Errorf("%s/%s:\n got %q\nwant %q", s.Instance, s.Name, got, want)
		}
	}
}

func TestWritePluginSkillsRewritesItsOwnSkill(t *testing.T) {
	dir := t.TempDir()
	write := func(content string) {
		t.Helper()
		if err := WritePluginSkills(dir, testSkillsDir, []PluginSkill{{Instance: "t", Name: "w", Content: []byte(content)}}); err != nil {
			t.Fatal(err)
		}
	}
	write("old\n")
	write("new\n")
	if got := readSkill(t, dir, "plugin-t-w"); got != PluginSkillMarker("t")+"\nnew\n" {
		t.Fatalf("own skill not rewritten: %q", got)
	}
}

// A destination the generator did not write is the user's: refused by
// path, left as it was, and nothing else is written either.
func TestWritePluginSkillsRefusesAConflict(t *testing.T) {
	for _, tc := range []struct {
		name  string
		setup func(t *testing.T, dir string) string
	}{{
		name: "skill without marker",
		setup: func(t *testing.T, dir string) string {
			return filepath.Dir(writeSkillFile(t, dir, "plugin-t-w", "# mine\n"))
		},
	}, {
		name: "marker not on the first line",
		setup: func(t *testing.T, dir string) string {
			return filepath.Dir(writeSkillFile(t, dir, "plugin-t-w", "# mine\n"+PluginSkillMarker("t")+"\n"))
		},
	}, {
		name: "directory with other files and no skill",
		setup: func(t *testing.T, dir string) string {
			d := filepath.Join(dir, testSkillsDir, "plugin-t-w")
			if err := os.MkdirAll(d, 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(filepath.Join(d, "notes.md"), []byte("mine"), 0o644); err != nil {
				t.Fatal(err)
			}
			return d
		},
	}, {
		name: "a file where the directory goes",
		setup: func(t *testing.T, dir string) string {
			d := filepath.Join(dir, testSkillsDir)
			if err := os.MkdirAll(d, 0o755); err != nil {
				t.Fatal(err)
			}
			path := filepath.Join(d, "plugin-t-w")
			if err := os.WriteFile(path, []byte("mine"), 0o644); err != nil {
				t.Fatal(err)
			}
			return path
		},
	}, {
		name: "a symlink where the directory goes",
		setup: func(t *testing.T, dir string) string {
			target := t.TempDir()
			if err := os.WriteFile(filepath.Join(target, "SKILL.md"), []byte(PluginSkillMarker("t")+"\n"), 0o644); err != nil {
				t.Fatal(err)
			}
			d := filepath.Join(dir, testSkillsDir)
			if err := os.MkdirAll(d, 0o755); err != nil {
				t.Fatal(err)
			}
			path := filepath.Join(d, "plugin-t-w")
			if err := os.Symlink(target, path); err != nil {
				t.Fatal(err)
			}
			return path
		},
	}} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			path := tc.setup(t, dir)
			before := snapshotTree(t, dir)
			err := WritePluginSkills(dir, testSkillsDir, []PluginSkill{
				{Instance: "a", Name: "first", Content: []byte("a\n")},
				{Instance: "t", Name: "w", Content: []byte("t\n")},
			})
			if !errors.Is(err, ErrPluginSkillConflict) {
				t.Fatalf("err = %v, want ErrPluginSkillConflict", err)
			}
			if !strings.Contains(err.Error(), path) {
				t.Errorf("error does not name %s: %v", path, err)
			}
			if after := snapshotTree(t, dir); after != before {
				t.Errorf("a refused write changed the directory:\nbefore %s\nafter  %s", before, after)
			}
		})
	}
}

