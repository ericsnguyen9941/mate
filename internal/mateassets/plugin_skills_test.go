// Built-in skills written by Write and plugin skills share the directory;
// each write leaves the other's alone.
func TestWriteAndPluginSkillsLeaveEachOtherAlone(t *testing.T) {
	dir := t.TempDir()
	p := fixedParams()
	if err := Write(dir, p); err != nil {
		t.Fatal(err)
	}
	if err := WritePluginSkills(dir, p.SkillsDir, []PluginSkill{{Instance: "t", Name: "w", Content: []byte("x\n")}}); err != nil {
		t.Fatal(err)
	}
	if err := Write(dir, p); err != nil {
		t.Fatal(err)
	}
	if got := readSkill(t, dir, "plugin-t-w"); got != PluginSkillMarker("t")+"\nx\n" {
		t.Errorf("Write touched a plugin skill: %q", got)
	}
	for _, name := range SkillNames {
		want, err := RenderSkill(name, p)
		if err != nil {
			t.Fatal(err)
		}
		if got := readSkill(t, dir, name); !bytes.Equal([]byte(got), want) {
			t.Errorf("WritePluginSkills touched built-in %s", name)
		}
	}
}

// snapshotTree lists every path under dir with its bytes, so a test can
// prove a refused call wrote nothing.
func snapshotTree(t *testing.T, dir string) string {
	t.Helper()
	var b strings.Builder
	err := filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		b.WriteString(path)
		if info.Mode().IsRegular() {
			data, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			b.WriteString("=" + string(data))
		}
		b.WriteString("\n")
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return b.String()
}
