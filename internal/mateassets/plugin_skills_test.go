func TestWritePluginSkillsRefusesBadInput(t *testing.T) {
	for _, tc := range []struct {
		name      string
		skillsDir string
		skills    []PluginSkill
	}{
		{"skills dir outside", "../skills", nil},
		{"empty instance", testSkillsDir, []PluginSkill{{Name: "w"}}},
		{"empty name", testSkillsDir, []PluginSkill{{Instance: "t"}}},
		{"name with a separator", testSkillsDir, []PluginSkill{{Instance: "t", Name: "a/b"}}},
		{"name of dots", testSkillsDir, []PluginSkill{{Instance: "t", Name: ".."}}},
		{"instance with a newline", testSkillsDir, []PluginSkill{{Instance: "t\n-->", Name: "w"}}},
		// Instance ids may hold "-", so two pairs can spell one directory.
		{"two skills, one directory", testSkillsDir, []PluginSkill{
			{Instance: "a-b", Name: "c"}, {Instance: "a", Name: "b-c"},
		}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			if err := WritePluginSkills(dir, tc.skillsDir, tc.skills); err == nil {
				t.Fatal("accepted")
			}
			if exists(t, filepath.Join(dir, testSkillsDir)) {
				t.Error("refused input still wrote")
			}
		})
	}
}

